    private void jbActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbActualizarActionPerformed
       if (jtfID.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Seleccione un socio de la tabla.");
        return;
    }

    try {
        Socio socio = new Socio();

        socio.setIdSocio(Integer.parseInt(jtfID.getText()));
        socio.setDni(jtfDNI.getText());
        socio.setApellido(jtfApellido.getText());
        socio.setNombre(jtfNombre.getText());
        socio.setEdad(Integer.parseInt(jtfEdad.getText()));
        socio.setCorreo(jtfCorreo.getText());
        socio.setTelefono(jtfTelefono.getText());
        socio.setEstado(jrbActivo.isSelected());

        SocioData socioData = new SocioData();
        socioData.actualizarSocio(socio);

        cargarTabla();
        JOptionPane.showMessageDialog(this, "Se actualizo correctamente.");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El ID y la edad deben ser números.");
}
    }//GEN-LAST:event_jbActualizarActionPerformed

    private void jbEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbEliminarActionPerformed
         if (jtfID.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Seleccione un socio.");
        return;
    }

    int respuesta = JOptionPane.showConfirmDialog(
        this,
        "¿Está seguro de eliminar este socio?",
        "Confirmar eliminación",
        JOptionPane.YES_NO_OPTION
    );

    if (respuesta == JOptionPane.YES_OPTION) {
        try {
            int id = Integer.parseInt(jtfID.getText());

            SocioData socioData = new SocioData();
            socioData.borrarSocio(id);

            cargarTabla();

            JOptionPane.showMessageDialog(this, "Se elimino correctamente el socio.");

            jtfID.setText("");
            jtfDNI.setText("");
            jtfApellido.setText("");
            jtfNombre.setText("");
            jtfEdad.setText("");
            jtfCorreo.setText("");
            jtfTelefono.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID debe ser un número.");
    }
    }
    }//GEN-LAST:event_jbEliminarActionPerformed

    private void jbAltaBajaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbAltaBajaActionPerformed
         if (jtfID.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Primero debe buscar un socio."
            );
            return;
        }

        try {
            int id = Integer.parseInt(jtfID.getText().trim());

            SocioData sd  = new SocioData();

            if (jrbActivo.isSelected()) {
                sd.bajaLogica(id);
                jrbInactivo.setSelected(true);
                javax.swing.JOptionPane.showMessageDialog(
                    this, "Socio dado de baja."
                );
            } else if (jrbInactivo.isSelected()) {
                sd.altaLogica(id);
                jrbActivo.setSelected(true);
                javax.swing.JOptionPane.showMessageDialog(
                    this, "Socio dado de alta."
                );
            } else {
                javax.swing.JOptionPane.showMessageDialog(
                    this, "Seleccione Activo o Inactivo."
                );
            }
            cargarTabla();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "ID incorrecto."
            );
        }    
    }//GEN-LAST:event_jbAltaBajaActionPerformed
    private void cargarTabla() {
    DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
    modelo.setRowCount(0);

    SocioData socioData = new SocioData();

    for (Socio s : socioData.listarSocios()) {
        modelo.addRow(new Object[]{
            s.getIdSocio(),
            s.getDni(),
            s.getNombre(),
            s.getApellido(),
            s.getEdad(),
            s.getCorreo(),
            s.getTelefono(),
            s.isEstado() ? "Activo" : "Inactivo"
        });
    }
}
    private void jbGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbGuardarActionPerformed
                                        
    String dni = jtfDNI.getText();
    String apellido = jtfApellido.getText();
    String nombre = jtfNombre.getText();
    String telefono = jtfTelefono.getText();
    String correo = jtfCorreo.getText();

    if (dni.isEmpty() || apellido.isEmpty() || nombre.isEmpty()
            || telefono.isEmpty() || correo.isEmpty()
            || jtfEdad.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Debe ompletar todos los campos.");
        return;
    }

    int edad;

    try {
        edad = Integer.parseInt(jtfEdad.getText());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "La edad debe ser un número.");
        return;
    }

    boolean estado = jrbActivo.isSelected();

    Socio socio = new Socio();
    socio.setDni(dni);
    socio.setApellido(apellido);
    socio.setNombre(nombre);
    socio.setTelefono(telefono);
    socio.setEdad(edad);
    socio.setCorreo(correo);
    socio.setEstado(estado);

    SocioData socioData = new SocioData();
    socioData.guardarSocio(socio);
    cargarTabla();

    JOptionPane.showMessageDialog(this, " El Socio se ha guardado correctamente.");
    }//GEN-LAST:event_jbGuardarActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String dni = jtfDNI.getText().trim();
        if(dni.isEmpty()){
            JOptionPane.showMessageDialog(this, "Ingrese un dni para buscar.");
            return;
        }
        SocioData socioData = new SocioData();
        Socio s = socioData.buscarSocio(dni);
        
        if(s != null){
            jtfID.setText(String.valueOf(s.getIdSocio()));
            jtfNombre.setText(s.getNombre());
            jtfApellido.setText(s.getApellido());
            jtfEdad.setText(String.valueOf(s.getEdad()));
            jtfCorreo.setText(s.getCorreo());
            jtfTelefono.setText(s.getTelefono());
            
            if(s.isEstado()){
                jrbActivo.setSelected(true);
            } else{
                jrbInactivo.setSelected(true);
            }
        } else{
            JOptionPane.showMessageDialog(this, "No se encontró ningún socio con ese dni.");
        }        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();
        if(fila != -1){
            jtfID.setText(jTable1.getValueAt(fila, 0).toString());
            jtfDNI.setText(jTable1.getValueAt(fila, 1).toString());
            jtfNombre.setText(jTable1.getValueAt(fila, 2).toString());
            jtfApellido.setText(jTable1.getValueAt(fila, 3).toString());
            jtfEdad.setText(jTable1.getValueAt(fila, 4).toString());
            jtfCorreo.setText(jTable1.getValueAt(fila, 5).toString());
            jtfTelefono.setText(jTable1.getValueAt(fila, 6).toString());
            
            String estado = jTable1.getValueAt(fila, 7).toString();
            
            if(estado.equalsIgnoreCase("Activo")){
                jrbActivo.setSelected(true);
            } else {
                jrbInactivo.setSelected(true);
            }
        }
    }//GEN-LAST:event_jTable1MouseClicked

