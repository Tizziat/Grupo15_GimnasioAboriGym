    private void cargarTabla() {
        modelo.setRowCount(0);

        for (Pase p : paseData.listarPases()) {
            modelo.addRow(new Object[]{
                p.getIdPase(),
                p.getSocio().getIdSocio(),
                p.getCantidadEntradas(),
                p.getFechaInicio(),
                p.getFechaFin(),
                p.getCosto(),
                p.isEstado() ? "Activo" : "Inactivo"
            });
        }
    }

